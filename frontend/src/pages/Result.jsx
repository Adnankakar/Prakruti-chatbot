import { useEffect } from 'react'
import { useNavigate } from 'react-router-dom'
import { RotateCcw, Home } from 'lucide-react'
import Logo from '../components/common/Logo'
import Button from '../components/common/Button'
import DominantDoshaCard from '../components/results/DominantDoshaCard'
import DoshaChart from '../components/results/DoshaChart'
import RecommendationSection from '../components/results/RecommendationSection'
import ResultDisclaimer from '../components/results/ResultDisclaimer'
import ErrorState from '../components/common/ErrorState'
import { useAssessment } from '../context/AssessmentContext'

export default function Result() {
  const navigate = useNavigate()
  const { result, reset, status } = useAssessment()

  // Guard: if no result, redirect home
  useEffect(() => {
    if (!result && status !== 'submitting') {
      navigate('/', { replace: true })
    }
  }, [result, status, navigate])

  function handleRetake() {
    reset()
    navigate('/')
  }

  if (!result) return null

  return (
    <div className="min-h-screen bg-surface">
      {/* Header */}
      <header className="border-b border-stone-200 bg-white/80 backdrop-blur-sm sticky top-0 z-10">
        <div className="max-w-3xl mx-auto px-6 py-4 flex items-center justify-between">
          <Logo size="sm" />
          <Button variant="ghost" onClick={handleRetake} className="text-sm gap-1.5">
            <RotateCcw size={14} />
            Retake
          </Button>
        </div>
      </header>

      <main className="max-w-2xl mx-auto px-6 py-10 space-y-6 animate-fade-in">
        {/* Page title */}
        <div className="space-y-1">
          <h1 className="text-2xl font-serif text-stone-900">Your Prakruti Assessment</h1>
          <p className="text-sm text-stone-500">
            Assessment completed. Results generated by the backend scoring and classification system.
          </p>
        </div>

        {/* Dominant Dosha */}
        <DominantDoshaCard prediction={result.ml_prediction} />

        {/* VPK Chart */}
        <DoshaChart vpk={result.vpk_percentages} />

        {/* Disclaimer — always visible */}
        <ResultDisclaimer />

        {/* Recommendations */}
        <RecommendationSection recommendation={result.recommendation} />

        {/* Backend disclaimer */}
        {result.disclaimer && (
          <p className="text-xs text-stone-400 text-center leading-relaxed">
            {result.disclaimer}
          </p>
        )}

        {/* Actions */}
        <div className="flex flex-col sm:flex-row gap-3 pt-2">
          <Button variant="secondary" onClick={handleRetake} className="flex-1">
            <Home size={16} />
            Back to Home
          </Button>
          <Button onClick={handleRetake} className="flex-1">
            <RotateCcw size={16} />
            Retake Assessment
          </Button>
        </div>
      </main>

      <footer className="text-center py-8 text-xs text-stone-400">
        Prakruti Self-Assessment · Final Year Engineering Project · Educational Use Only
      </footer>
    </div>
  )
}
